<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class User extends Authenticatable
{
    use HasFactory, Notifiable;

    protected $table = 'users';
    protected $primaryKey = 'user_id';
    public $incrementing = true;
    protected $keyType = 'int';

    /**
     * Mass assignable attributes.
     */
    protected $fillable = [
        'employee_id',
        'username',
        'email',
        'password_hash',
        'role',
        'is_active',
    ];

    /**
     * Hidden attributes for arrays / serialization.
     */
    protected $hidden = [
        'password_hash',
        'remember_token',
    ];

    /**
     * Attribute casting.
     */
    protected $casts = [
        'is_active' => 'boolean',
    ];

    /**
     * Overrides default password column name for Laravel authentication.
     */
    public function getAuthPassword(): string
    {
        return $this->password_hash;
    }

    /**
     * Associated employee profile.
     */
    public function employee(): BelongsTo
    {
        return $this->belongsTo(Employee::class, 'employee_id', 'employee_id');
    }

    /**
     * Document routing logs scanned / recorded by this user.
     */
    public function routingLogs(): HasMany
    {
        return $this->hasMany(RoutingLog::class, 'scanned_by', 'user_id');
    }

    /**
     * Attendance deduction summaries encoded by this HR user.
     */
    public function attendanceDeductions(): HasMany
    {
        return $this->hasMany(AttendanceDeduction::class, 'encoded_by', 'user_id');
    }

    /**
     * Starla conversion table references calibrated or validated by this admin.
     */
    public function validatedStarlaReferences(): HasMany
    {
        return $this->hasMany(StarlaReference::class, 'validated_by', 'user_id');
    }

    /**
     * Audit trail entries generated by this user.
     */
    public function auditLogs(): HasMany
    {
        return $this->hasMany(AuditLog::class, 'user_id', 'user_id');
    }

    /*
    |--------------------------------------------------------------------------
    | RBAC Role Check Helpers
    |--------------------------------------------------------------------------
    */

    public function isAdmin(): bool
    {
        return $this->role === 'admin';
    }

    public function isHrmuStaff(): bool
    {
        return $this->role === 'hrmu_staff';
    }

    public function isRoutingClerk(): bool
    {
        return $this->role === 'routing_clerk';
    }

    /**
     * Checks if the user is the Municipal Mayor or stationed at the Office of the Municipal Mayor.
     */
    public function isMayor(): bool
    {
        $userOfficeId = (int) ($this->employee?->office_id ?? 0);
        $position = $this->employee?->position ?? '';
        $officeName = $this->employee?->office?->office_name ?? '';

        return $userOfficeId === 2
            || stripos($this->username, 'mayor') !== false
            || (stripos($position, 'mayor') !== false && stripos($position, 'vice') === false)
            || (stripos($officeName, 'mayor') !== false && stripos($officeName, 'vice') === false);
    }

    /**
     * Checks if the user is authorized to access and operate the QR Document Scanner terminal.
     * Authorized: routing_clerk, hrmu_staff, admin, department heads, and mayor.
     * Standard employees are excluded.
     */
    public function canAccessQrScanner(): bool
    {
        if (in_array($this->role, ['routing_clerk', 'hrmu_staff', 'admin'])) {
            return true;
        }

        if ($this->isMayor() || $this->isDepartmentHead()) {
            return true;
        }

        return false;
    }

    /**
     * Any authenticated active municipal employee/staff can act as the receiving/routing clerk in their office.
     */
    public function canActAsReceiver(): bool
    {
        return (bool) $this->is_active && $this->canAccessQrScanner();
    }

    public function isEmployee(): bool
    {
        return $this->role === 'employee';
    }

    /**
     * Checks if the user is a Department Head, Head of Office, or Recommending Officer.
     *
     * @param int|null $officeId Optional office ID to check if head of a specific office
     * @return bool
     */
    public function isDepartmentHead(?int $officeId = null): bool
    {
        // 1. Explicit username indicator (e.g. emp_depthead)
        if (stripos($this->username, 'depthead') !== false || stripos($this->username, 'dept_head') !== false) {
            if ($officeId !== null && $this->employee?->office_id) {
                return (int) $this->employee->office_id === (int) $officeId;
            }
            return true;
        }

        $position = $this->employee?->position ?? '';
        if (empty($position)) {
            return false;
        }

        $headKeywords = [
            'head',
            'coordinator',
            'chief',
            'director',
            'administrator',
            'officer-in-charge',
            'oic',
            'municipal planning',
            'health officer',
            'municipal engineer',
            'municipal agriculturist',
            'municipal assessor',
            'budget officer',
            'accountant',
            'treasurer',
            'civil registrar',
            'general services officer',
        ];

        foreach ($headKeywords as $keyword) {
            if (stripos($position, $keyword) !== false) {
                if ($officeId !== null && $this->employee?->office_id) {
                    return (int) $this->employee->office_id === (int) $officeId;
                }
                return true;
            }
        }

        return false;
    }

    /**
     * Determines whether the user is authorized to view an application's Form 6
     * and associated digital supporting documents.
     *
     * Permitted actors:
     * - System Administrators (Full oversight)
     * - HRMU Staff / Record Keepers (Verification & Ledger Processing)
     * - Routing / Receiving Clerks (Custody & Tracking)
     * - The Applicant Employee (Self-Service)
     * - Appointing Authority (Municipal Mayor & Mayor's Office Staff)
     * - Department Heads / Heads of Office (Section 7.B Recommendation & Office Oversight)
     * - Municipal Personnel assigned to the applicant's department or current routing station
     * - Personnel who have processed/scanned the physical document
     */
    public function canViewApplicationDocument(LeaveApplication $application): bool
    {
        // 1. System Admins, HRMU Staff, and Routing Clerks have universal oversight
        if ($this->isAdmin() || $this->isHrmuStaff() || $this->isRoutingClerk()) {
            return true;
        }

        // 2. Department Heads / Recommending Officers can view all leave applications and supporting documents
        if ($this->isDepartmentHead()) {
            return true;
        }

        // 3. The applicant themself can always view their own application documents
        if ($this->employee_id && (int) $this->employee_id === (int) $application->employee_id) {
            return true;
        }

        $userOfficeId = (int) ($this->employee?->office_id ?? 0);
        $applicantOfficeId = (int) ($application->employee?->office_id ?? 0);
        $currentLocationId = (int) ($application->current_location_office_id ?? 0);

        // 4. Office of the Municipal Mayor (Appointing Authority)
        if ($userOfficeId === 2 
            || stripos($this->employee?->office?->office_name ?? '', 'mayor') !== false 
            || stripos($this->employee?->position ?? '', 'mayor') !== false) {
            return true;
        }

        // 5. Personnel assigned to the applicant's department or the current document custody office
        if ($userOfficeId > 0 && ($userOfficeId === $applicantOfficeId || $userOfficeId === $currentLocationId)) {
            return true;
        }

        // 6. Personnel who previously acted on / scanned this document in routing
        if ($application->relationLoaded('routingLogs')) {
            if ($application->routingLogs->contains('scanned_by', $this->user_id)) {
                return true;
            }
        } elseif ($application->routingLogs()->where('scanned_by', $this->user_id)->exists()) {
            return true;
        }

        return false;
    }

    public function hasRole(string|array $roles): bool
    {
        if (is_array($roles)) {
            return in_array($this->role, $roles);
        }
        return $this->role === $roles;
    }
}
